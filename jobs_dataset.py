REQUIRED_FIELDS = (
    "job_id", "job_title", "company", "location", "job_description",
    "responsibilities", "required_skills", "qualifications",
)


def _unique(items):
    seen, out = set(), []
    for item in items or []:
        key = str(item).strip().lower()
        if key and key not in seen:
            seen.add(key)
            out.append(str(item).strip())
    return out


def _clean_dataset(records):
    """M2.1 cleaning: de-duplicate skill lists, drop incomplete or exact-duplicate postings."""
    cleaned, seen_ids, seen_content = [], set(), set()
    for record in records:
        record = dict(record)
        record["required_skills"] = _unique(record.get("required_skills"))
        record["preferred_skills"] = [
            s for s in _unique(record.get("preferred_skills"))
            if s.lower() not in {r.lower() for r in record["required_skills"]}
        ]
        if any(not record.get(field) for field in REQUIRED_FIELDS):
            continue
        content = tuple(
            (k, str(v)) for k, v in sorted(record.items()) if k != "job_id"
        )
        if record["job_id"] in seen_ids or content in seen_content:
            continue
        seen_ids.add(record["job_id"])
        seen_content.add(content)
        cleaned.append(record)
    return cleaned


INTERNSHIP_DATASET = _clean_dataset(INTERNSHIP_DATASET)


def dataset_quality_report():
    """Summary used by documentation and the evaluation scripts."""
    from collections import Counter
    return {
        "postings": len(INTERNSHIP_DATASET),
        "domains": dict(Counter(j["domain"] for j in INTERNSHIP_DATASET)),
        "locations": dict(Counter(j["location"] for j in INTERNSHIP_DATASET)),
        "avg_required_skills": round(
            sum(len(j["required_skills"]) for j in INTERNSHIP_DATASET) / max(len(INTERNSHIP_DATASET), 1), 2
        ),
    }


def get_all_jobs():
    """Return a copy of the complete internship dataset."""
    return [job.copy() for job in INTERNSHIP_DATASET]


def get_job(job_id):
    """Return one job by its benchmark ID, or None if it does not exist."""
    return next((job.copy() for job in INTERNSHIP_DATASET if job["job_id"] == job_id), None)


